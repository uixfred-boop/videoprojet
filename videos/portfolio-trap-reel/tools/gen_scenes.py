def title(p, l1, l2):
    return (f'<div class="lr-title" id="{p}-title"><span class="l1" id="{p}-l1">{l1}</span>'
            f'<span class="l2"><span class="bar" id="{p}-bar"></span><span class="tx" id="{p}-l2">{l2}</span></span></div>')


def title_js(p, t0, dur=0.55):
    """The reference types a 2-line title in ~0.55s, line 2's red bar growing with it."""
    mid = t0 + dur * 0.5
    return f"""          fx.typeSpan(tl, "#{p}-l1", at({t0:.2f}), at({mid:.2f}), {{ hidden: true }});
          fx.typeSpan(tl, "#{p}-l2", at({mid:.2f}), at({t0 + dur:.2f}), {{ hidden: true }});
          fx.grow(tl, "#{p}-bar", at({mid:.2f}), at({t0 + dur:.2f}));"""


ITEMS = [("01", "Projects, Not Results"), ("02", "Nobody Gets What You Sell"), ("03", "No Next Step")]
ROW_TOP = [470, 660, 850]


def rows(p, active=None):
    """active=None: the hub (every row has its bar); active=i: a hub return, only row i keeps its bar."""
    out = []
    for i, (n, label) in enumerate(ITEMS):
        hide = ' style="opacity: 0"' if active is not None and i != active else ""
        out.append(f'<div class="lr-row" id="{p}-r{i}" style="top: {ROW_TOP[i]}px"><span class="bar" id="{p}-b{i}"{hide}>'
                   f'<span class="edge"></span><span class="sheen" id="{p}-s{i}"></span></span>'
                   f'<span class="num">{n}</span><span class="lbl" id="{p}-t{i}">{label}</span></div>')
    return "\n        ".join(out)


def crumb(p, i):
    n, label = ITEMS[i]
    return f'<div class="lr-crumb" id="{p}-crumb"><span class="edge"></span><span class="num">{n}</span><span class="lbl">{label}</span></div>'


def crumb_js(p):
    return f"""          tl.fromTo("#{p}-crumb", {{ opacity: 0, x: 50 }}, {{ opacity: 1, x: 0, duration: 0.4, ease: "power3.out" }}, 0.02);"""


def hub_return(p, active, t0, t_label):
    """Hub after a cut: the list is already there, only the active row keeps its bar; the title re-types."""
    js = [title_js(p, t0 + 0.03)]
    js.append(f'          tl.fromTo("#{p}-r{active}", {{ scale: 1 }}, {{ scale: 1.04, duration: 0.35, ease: "power2.out" }}, at({t_label:.2f}));')
    js.append(f'          tl.fromTo("#{p}-t{active}", {{ filter: "blur(7px)" }}, {{ filter: "blur(0px)", duration: 0.3, ease: "power2.out" }}, at({t_label:.2f}));')
    js.append(f'          fx.sheen(tl, "#{p}-s{active}", at({t_label + 0.08:.2f}));')
    js.append(f'          fx.push(tl, "#{p}-list", 0, 2.6, 1.03);')
    return "\n".join(js)


