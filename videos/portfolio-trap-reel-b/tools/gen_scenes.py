def hub_body(p, active=None, extra_ph="", rows_extra=None, blur=True, page_extra=""):
    """active=None: every row has its bar (the first hub); active=i: a hub return, only row i keeps its bar."""
    boxes = "".join(f'<div class="ann-box" id="{p}-x{i}" style="left: {x}px; top: {y}px; width: {w}px; height: {h}px"></div>'
                    for i, (x, y, w, h) in enumerate(BOXES))
    rows, marks = [], []
    for i, (n, label) in enumerate(ITEMS):
        hide = ' style="opacity: 0"' if active is not None and i != active else ""
        lbl_style = "" if blur else ' style="filter: none"'
        more = rows_extra(i) if rows_extra else ""
        rows.append(f'<div class="lr-row ann" id="{p}-r{i}" style="top: {ANCHOR[i] - 52}px"><span class="bar" id="{p}-b{i}"{hide}>'
                    f'<span class="edge" id="{p}-e{i}"></span><span class="sheen" id="{p}-s{i}"></span></span>'
                    f'<span class="num">{n}</span><span class="lbl" id="{p}-t{i}"{lbl_style}>{label}</span>{more}</div>')
        marks.append(f'<i class="ann-ln" id="{p}-l{i}" style="top: {ANCHOR[i] - 1.5}px"></i>'
                     f'<i class="ann-dot" id="{p}-d{i}" style="top: {ANCHOR[i] - 10}px"></i>')
