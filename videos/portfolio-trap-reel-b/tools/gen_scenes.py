GRID_TOP, TH_W, TH_H, TH_GAP = 156, 171, 124, 12


def page_layout(n):
    rows = (n + 1) // 2
    gb = GRID_TOP + rows * TH_H + (rows - 1) * TH_GAP    # grid bottom
    ab = gb + 30                                         # "About" top
    ct = ab + 150                                        # "Contact" top
    return gb, ab, ct


def thumb_xy(i):
    return 24 + (i % 2) * (TH_W + 12), GRID_TOP + (i // 2) * (TH_H + TH_GAP)


