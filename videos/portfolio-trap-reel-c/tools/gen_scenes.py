HEAD = """<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
  </head>
  <body>
    <!-- Generated by tools/gen_scenes.py: edit the generator, not this file. -->
    <template id="{sid}-template">
{link}      <style>
{fonts}{css}
      </style>
"""
TAIL = """      <script>
        (function () {{
          const T0 = {t0};
          const at = (t) => Math.max(0, t - T0);
          const tl = gsap.timeline({{ paused: true }});
          const root = document.querySelector('[data-composition-id="{sid}"]');
{js}
          window.__timelines["{sid}"] = tl;
        }})();
      </script>
    </template>
  </body>
</html>
"""


def panel(sid, t0, t1, css, body, js):
    html = (HEAD.format(sid=sid, fonts=FONTS, css=ROOT_CSS + css, link=LINK)
            + f"""      <div id="root" data-composition-id="{sid}" data-width="1080" data-height="1920">
        <div class="lr-bg" data-layout-allow-overflow></div>
{body}
      </div>
""" + TAIL.format(t0=t0, js=js, sid=sid))
    (ROOT / f"compositions/{sid}.html").write_text(html)


def cut(sid, t0, t1, media_start, rate=0.8, origin="55% 18%", s0=1.32, s1=1.38):  # noqa: PLR0913
    """Full-screen cutaway of the user's footage: tight, hard cut in, slow push (the caption lives in captions.html)."""
    p = sid.split("-")[0]
    assert media_start + (t1 - t0) * rate <= 13.85, f"{sid} runs past the footage"
    css = f"""        #root {{ position: absolute; inset: 0; overflow: hidden; background: #000; }}
        #{p}-cam {{ position: absolute; inset: 0; transform-origin: {origin}; }}
        #{p}-cam video {{ position: absolute; left: 0; top: 0; width: 1080px; height: 1920px; object-fit: cover; }}
        #{p}-shade {{ position: absolute; inset: 0; background: radial-gradient(ellipse 85% 65% at 50% 30%, rgba(0,0,0,0) 0%, rgba(0,0,0,0.28) 100%), linear-gradient(180deg, rgba(0,0,0,0) 55%, rgba(0,0,0,0.32) 100%); }}"""
    html = (HEAD.format(sid=sid, fonts=FONTS, css=css, link="")
            + f"""      <div id="root" data-composition-id="{sid}" data-width="1080" data-height="1920">
        <div id="{p}-cam" data-layout-allow-overflow>
          <video id="{p}-v" class="clip" src="assets/video/desk.mp4" data-start="0" data-duration="{t1 - t0:.2f}" data-media-start="{media_start}" data-playback-rate="{rate}" data-track-index="0" muted playsinline></video>
        </div>
        <div id="{p}-shade"></div>
      </div>
""" + TAIL.format(t0=t0, sid=sid, js=f"""          tl.fromTo("#{p}-cam", {{ scale: {s0} }}, {{ scale: {s1}, duration: {t1 - t0:.2f}, ease: "none" }}, 0);"""))
    (ROOT / f"compositions/{sid}.html").write_text(html)


# ---------------------------------------------------------------- shared pieces
def title(p, l1, l2):
    return (f'<div class="lr-title" id="{p}-title"><span class="l1" id="{p}-l1">{l1}</span>'
            f'<span class="l2"><span class="bar" id="{p}-bar"></span><span class="tx" id="{p}-l2">{l2}</span></span></div>')


def title_js(p, t0, dur=0.55):
    """The reference types a 2-line title in ~0.55s, line 2's red bar growing with it."""
    mid = t0 + dur * 0.5
    return f"""          fx.typeSpan(tl, "#{p}-l1", at({t0:.2f}), at({mid:.2f}), {{ hidden: true }});
          fx.typeSpan(tl, "#{p}-l2", at({mid:.2f}), at({t0 + dur:.2f}), {{ hidden: true }});
          fx.grow(tl, "#{p}-bar", at({mid:.2f}), at({t0 + dur:.2f}));"""


def head(p, text):
    """Single-line header with the red underline (the reference's second header variant)."""
    return f'<div class="lr-head" id="{p}-head"><span class="w"><span id="{p}-h">{text}</span><span class="ul" id="{p}-ul"></span></span></div>'


def head_js(p, t0, t1):
    return f"""          fx.typeSpan(tl, "#{p}-h", at({t0:.2f}), at({t1:.2f}), {{ hidden: true }});
          fx.grow(tl, "#{p}-ul", at({t0:.2f}), at({t1:.2f}));"""


ITEMS = [("01", "Projects, Not Results"), ("02", "Nobody Gets What You Sell"), ("03", "No Next Step")]
ROW_TOP = [470, 660, 850]


def rows(p):
    out = []
    for i, (n, label) in enumerate(ITEMS):
        out.append(f'<div class="lr-row" id="{p}-r{i}" style="top: {ROW_TOP[i]}px"><span class="bar" id="{p}-b{i}">'
                   f'<span class="edge"></span><span class="sheen" id="{p}-s{i}"></span></span>'
                   f'<span class="num">{n}</span><span class="lbl" id="{p}-t{i}">{label}</span></div>')
    return "\n        ".join(out)


def crumb(p, i):
    n, label = ITEMS[i]
    return f'<div class="lr-crumb" id="{p}-crumb"><span class="edge"></span><span class="num">{n}</span><span class="lbl">{label}</span></div>'


def crumb_js(p):
    return f"""          tl.fromTo("#{p}-crumb", {{ opacity: 0, x: 50 }}, {{ opacity: 1, x: 0, duration: 0.4, ease: "power3.out" }}, 0.02);"""


def cx(top, inner):
    """Centre an element horizontally without a CSS translate (GSAP owns the element's transform)."""
    return f'<div class="lr-cx" style="top: {top}px">{inner}</div>'


def slam(sel, t, frm=1.5, dur=0.28):
    """A word slams in: big and blurred to its place, fast, no bounce."""
    return (f'          tl.fromTo("{sel}", {{ opacity: 0, scale: {frm}, filter: "blur(14px)" }}, '
            f'{{ opacity: 1, scale: 1, filter: "blur(0px)", duration: {dur}, ease: "power4.out" }}, at({t:.2f}));')


def ghost(p, n, top=520):
    return cx(top, f'<div class="ghost" id="{p}-gn">{n}</div>')


def ghost_js(p, t_in, t_out):
    """The item number slams in as a giant outline on "One / Two / Three", then clears for the statement."""
    return (f'          tl.fromTo("#{p}-gn", {{ opacity: 0, scale: 1.5, filter: "blur(12px)" }}, {{ opacity: 1, scale: 1, filter: "blur(0px)", duration: 0.25, ease: "power4.out" }}, at({t_in:.2f}));\n'
            f'          tl.to("#{p}-gn", {{ opacity: 0, scale: 0.85, duration: 0.2, ease: "power2.in" }}, at({t_out:.2f}));')


